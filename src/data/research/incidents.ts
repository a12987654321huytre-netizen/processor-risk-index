export function mergeIncidents(existing: Incident[], extras: Incident[]): Incident[] {
  const seen = new Set(existing.map((i) => i.id));
  const groups = new Set(existing.map((i) => i.duplicateGroup).filter(Boolean));
  const out = [...existing];
  for (const inc of extras) {
    if (seen.has(inc.id)) continue;
    if (inc.duplicateGroup && groups.has(inc.duplicateGroup) && existing.some((e) => e.duplicateGroup === inc.duplicateGroup)) {
      // Same merchant story, different URL — skip as a separate pattern, keep as a source on the original if needed.
      continue;
    }
    seen.add(inc.id);
    if (inc.duplicateGroup) groups.add(inc.duplicateGroup);
    out.push(inc);
  }
  return out;
}
